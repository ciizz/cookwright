// src/lib/secret/backends/age.mjs — the age backend (stage-5 plan §4.3): a target's
// values in `secrets/<target>.env.age`, armored ciphertext tracked in the repo,
// encrypted to the public keys of `secrets/recipients.txt`; the identity that opens
// it lives outside every git work tree (dispositions 6, 51, 71), at
// `$COOKWRIGHT_AGE_IDENTITY`, else `$XDG_CONFIG_HOME/cookwright/identity.age`, else
// `~/.config/cookwright/identity.age`.
//
// cookwright never handles a passphrase: age prompts on the terminal it opens
// itself, so a call that may prompt is uncapped, and refused before it runs when
// there is no terminal (dispositions 40, 67). The plaintext lives in memory only:
// it goes to `age` on stdin and comes back on stdout. `age` and `age-keygen` run
// with the scrubbed environment the engine hands in `ctx.env`.
//
// Measured on age 1.3.2 (stage-5 s2): with an empty passphrase, `age -p` prints its
// "using autogenerated passphrase" line to the terminal it opened, not to stderr,
// so the stderr check below fires only where age has no terminal to print to; the
// consent text says what an empty passphrase does.

import fs from 'node:fs';
import path from 'node:path';

import { gitRun } from '../../doctor/repo.mjs';
import { messages } from '../../messages.mjs';
import { fail, pass, skip, warn } from '../../verdict.mjs';
import { RECIPIENTS, ciphertextOf, topRel } from '../config.mjs';
import { Refused } from '../engine.mjs';
import { parseAgainst, replaceLine } from '../envfile.mjs';
import { requireCommittedRecipients } from '../recipients.mjs';

const m = messages.secrets;
const a = m.age;
const b = messages.doctor.secretsBackend;
const t = messages.doctor.secretsTargets;

export const IDENTITY_ENV = 'COOKWRIGHT_AGE_IDENTITY';
/** The first line of a binary age file: a passphrase-protected identity starts so (disposition 7). */
export const HEADER = 'age-encryption.org/v1\n';
const ARMOR = '-----BEGIN AGE ENCRYPTED FILE-----';

export const firstLine = (text) => (text ?? '').trim().split('\n')[0];

/** Where the identity lives (disposition 6). */
export function identityPath(env, home) {
  if (env[IDENTITY_ENV]) return path.resolve(env[IDENTITY_ENV]);
  const xdg = env.XDG_CONFIG_HOME;
  return path.join(xdg && path.isAbsolute(xdg) ? xdg : path.join(home, '.config'), 'cookwright', 'identity.age');
}

/** The nearest directory above `file` that exists (disposition 71). */
export function nearestExistingAncestor(file) {
  let dir = path.dirname(path.resolve(file));
  while (!fs.existsSync(dir) && path.dirname(dir) !== dir) dir = path.dirname(dir);
  return dir;
}

/**
 * The top of the git work tree holding `dir`, judged by its realpath, or null
 * (disposition 51). Only "not a git repository" passes; any other failure refuses.
 */
export function enclosingWorkTree(dir, env) {
  const real = fs.realpathSync(dir);
  const clean = { ...env, LC_ALL: 'C' };
  for (const name of ['GIT_DIR', 'GIT_WORK_TREE', 'GIT_INDEX_FILE', 'GIT_COMMON_DIR']) delete clean[name];
  const res = gitRun(real, ['rev-parse', '--show-toplevel'], { env: clean });
  if (res.status === 0) return res.stdout.trim();
  if (res.status === 128 && /not a git repository/i.test(res.stderr)) return null;
  throw new Refused(a.gitProbe(firstLine(res.stderr) || `exit ${res.status}`));
}

/** True when the identity is age-encrypted (a passphrase-protected identity), binary or armored. */
export function isPassphraseProtected(file) {
  const fd = fs.openSync(file, 'r');
  try {
    const head = Buffer.alloc(ARMOR.length);
    const n = fs.readSync(fd, head, 0, head.length, 0);
    const text = head.subarray(0, n).toString('latin1');
    return text.startsWith(HEADER) || text.startsWith(ARMOR);
  } finally {
    fs.closeSync(fd);
  }
}

/** The identity's path, refusing when it is absent. */
function requireIdentity(ctx) {
  const identity = identityPath(ctx.env, ctx.home);
  if (!fs.existsSync(identity)) throw new Refused(a.noIdentity(identity));
  return identity;
}

/** Refuse a passphrase-protected identity without a terminal; true when age will prompt. */
function promptsFor(identity, ctx) {
  const protect = isPassphraseProtected(identity);
  if (protect && !ctx.probes.terminal()) throw new Refused(a.protectedNoTerminal);
  return protect;
}

/** The plaintext of `file`, decrypted with the identity (uncapped when age prompts). */
function decrypt(file, identity, protect, ctx) {
  const opts = { env: ctx.env, cwd: ctx.root, ...(protect && { cap: null }) };
  const res = ctx.probes.capture('age', ['-d', '-i', identity, file], opts);
  if (res.status !== 0) throw new Refused(a.failed('age -d', firstLine(res.stderr || res.error?.message)));
  return res.stdout;
}

/** A parseAgainst problem as a refusal: a missing name names its `secrets set` line. */
function resolvedProblem(problem, target) {
  if (problem.why === 'missing') return new Refused(m.missingName(problem.name, target));
  return new Refused(m.resolved(target, m.envfile[problem.why](problem)));
}

/** `resolve`: the target's values from its ciphertext, read against its declared names (disposition 53). */
export function resolve(name, ctx) {
  const target = ctx.config.secrets.targets[name];
  const file = path.join(ctx.root, ciphertextOf(name));
  if (!fs.existsSync(file)) throw new Refused(m.missingName(target.names[0], name));
  const identity = requireIdentity(ctx);
  const text = decrypt(file, identity, promptsFor(identity, ctx), ctx);
  const read = parseAgainst(text, target.names);
  if (read.problem) throw resolvedProblem(read.problem, name);
  return new Map(target.names.map((n) => [n, read.values.get(n)]));
}

/** The recipients file's keys once it is committed and equal to HEAD (disposition 23); refuses otherwise. */
export function committedRecipients(ctx) {
  const rel = ctx.top && topRel(ctx.root, ctx.top, RECIPIENTS);
  if (!rel) throw new Refused(m.notWorkTree);
  const got = requireCommittedRecipients(ctx.top, rel);
  if (got.problem) throw new Refused(m.recipients(got.problem, RECIPIENTS));
  return got.keys;
}

/** `text` encrypted to the recipients file into `file`: a temp file beside it, then a rename. */
function encryptTo(file, text, ctx) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = path.join(path.dirname(file), `.${path.basename(file)}.${process.pid}.tmp`);
  try {
    const args = ['-a', '-R', path.join(ctx.root, RECIPIENTS), '-o', tmp];
    const res = ctx.probes.capture('age', args, { input: text, env: ctx.env, cwd: ctx.root });
    if (res.status !== 0) throw new Refused(a.failed('age -e', firstLine(res.stderr || res.error?.message)));
    fs.renameSync(tmp, file);
  } finally {
    fs.rmSync(tmp, { force: true });
  }
}

/**
 * `set`: `secret` of target `name` set to the value `ctx.readValue()` reads, every
 * check made before the value is asked for: the existing ciphertext is decrypted
 * and read against the declared names first (stage-5 review:engine finding 1).
 * Returns the recipients' keys.
 */
export async function set(name, secret, ctx) {
  const target = ctx.config.secrets.targets[name];
  if (!target.names.includes(secret)) throw new Refused(m.undeclared(secret, name));
  const keys = committedRecipients(ctx);
  const file = path.join(ctx.root, ciphertextOf(name));
  const existing = fs.existsSync(file);
  const identity = existing ? requireIdentity(ctx) : null;
  const text = existing ? decrypt(file, identity, promptsFor(identity, ctx), ctx) : '';
  const read = parseAgainst(text, target.names, { partial: true });
  if (read.problem) throw resolvedProblem(read.problem, name);
  const value = await ctx.readValue();
  let next;
  try {
    next = replaceLine(text, secret, value);
  } catch {
    throw new Refused(a.multiLine(secret));
  }
  encryptTo(file, next, ctx);
  return { keys };
}

/**
 * Doctor's `secrets.backend` on age (dispositions 7, 41, 51): the identity outside
 * every work tree, present, readable by its owner only, passphrase-protected by its
 * header. Nothing is decrypted, and the note never quotes the file.
 */
export function health(ctx) {
  const identity = identityPath(ctx.env, ctx.home);
  const top = enclosingWorkTree(nearestExistingAncestor(identity), ctx.env);
  if (top !== null) return fail(b.age.inWorkTree(identity, top));
  if (!fs.existsSync(identity)) {
    const tool = AGE.tools.init.find((name) => !ctx.probes.hasTool(name, { PATH: ctx.env.PATH ?? '' }));
    return tool ? skip(b.needsTool(tool, b.ops.init, a.install)) : warn(b.age.missing(identity));
  }
  const windows = ctx.platform === 'win32';
  const mode = fs.statSync(identity).mode & 0o777;
  if (!windows && mode & 0o077) return fail(b.age.mode(identity, mode.toString(8)));
  if (!isPassphraseProtected(identity)) return warn(b.age.noPassphrase(identity));
  return windows ? skip(b.age.windows(identity)) : pass(b.age.ok(identity));
}

/**
 * Doctor's look at what the targets share: the recipients file committed and equal
 * to HEAD (disposition 23). `{ parts, ok }`; a secret key in it FAILs.
 */
export function inspectShared(ctx) {
  const got = requireCommittedRecipients(ctx.top, topRel(ctx.root, ctx.top, RECIPIENTS));
  if (!got.problem) return { parts: [], ok: true };
  const verdict = got.problem.why === 'secretKey' ? fail : warn;
  return { parts: [verdict(m.recipients(got.problem, RECIPIENTS))], ok: false };
}

/**
 * Doctor's look at target `name` (disposition 45): its ciphertext present and
 * committed, nothing decrypted, so the names are not the claim. `ctx.states` maps
 * each backend file to its git state, `ctx.shared` is inspectShared's result.
 */
export function inspect(name, ctx) {
  const rel = ciphertextOf(name);
  const state = ctx.states.get(rel);
  if (state === 'missing') return warn(t.age.noCiphertext(name, rel));
  if (state !== 'tracked') return warn(t.file(name, rel, state));
  return pass(t.age.ok(name, ctx.shared.ok));
}

/** The age backend's description, as backends/index.mjs registers it with `init` (age-init.mjs). */
export const AGE = Object.freeze({
  name: 'age',
  tools: { resolve: ['age'], set: ['age'], init: ['age', 'age-keygen'] },
  install: a.install,
  control: [IDENTITY_ENV],
  /** The files `run`'s banner reports uncommitted, relative to the config root. */
  files: (target) => [ciphertextOf(target)],
  /** The files every target shares, which doctor reads as the targets' files. */
  sharedFiles: [RECIPIENTS],
  resolve,
  set,
  health,
  inspect,
  inspectShared,
});
