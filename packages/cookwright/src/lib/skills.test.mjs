describe('the setup skill', () => {
  const text = read('setup');

  it('has a recipe for every check doctor runs', () => {
    for (const check of Object.keys(CHECKS)) expect(text).toContain(`\`${check}\``);
  });

  it("names every row a declared pack adds, so a pack's line never ends the walkthrough unnamed", () => {
    const rows = packRowNames(PACKS);
    expect(rows).toEqual(expect.arrayContaining(['pack.expo.lint', 'pack.supabase.types']));
    for (const row of rows) expect(text).toContain(`\`${row}\``);
  });

  it('copies the pack defaults from npx cookwright packs rules, never retyped', () => {
    expect(text).toContain('`npx cookwright packs rules`');
    expect(text.slice(text.indexOf('## At the end'))).toContain('npx cookwright packs rules');
  });

  it.each(QUOTED)('quotes %j as the note doctor or init prints', (fragment, note) => {
    expect(note).toContain(fragment);
    expect(text).toContain(fragment);
  });

  it('acts on every PASS row of its recipe at the end, since the loop skips PASS lines', () => {
    const end = text.slice(text.indexOf('## At the end'));
    const notes = [...text.matchAll(/^\|.*\| PASS \| `(?:… )?([^`]+)`/gm)].map((m) => m[1]);
    expect(notes.length).toBeGreaterThan(0);
    for (const note of notes) expect(end).toContain(note);
  });
});

describe('the docs-audit skill', () => {
  const text = read('docs-audit');

  it('builds the args with the CLI, runs the named Workflow on a branch of its own, and commits by path', () => {
    for (const step of ['npx cookwright audit args', '--doc <path>[:<scope>]', "Workflow({ name: 'docs-audit'", 'git checkout -b docs-audit/<YYYY-MM-DD> <that branch>', 'refs/heads/docs-audit/<YYYY-MM-DD>', 'git diff', 'git add <each doc>']) {
      expect(text).toContain(step);
    }
    expect(text).toContain(messages.audit.defaultScope);
  });

  it("takes the setup skill's fill as it hands it over: committed on its branch, then audited there", () => {
    const setup = read('setup');
    const fill = setup.slice(setup.indexOf('**Filling a contract doc.**'));
    const branch = 'docs/fill-<doc name>';
    expect(fill).toContain(`git checkout -b ${branch}`);
    expect(fill).toContain('commit the fill by path on that branch');
    expect(fill.indexOf('commit the fill')).toBeLessThan(fill.indexOf('`docs-audit` skill'));
    expect(text).toContain('`git status --porcelain` prints nothing');
    expect(text).toContain(`the setup skill's \`${branch}\` handoff`);
  });

  it("names the Workflow the package ships under that name", () => {
    const workflow = fs.readFileSync(path.join(PACKAGE_ROOT, 'hosts/claude/workflows/docs-audit.js'), 'utf8');
    expect(workflow).toMatch(/^\s*name: 'docs-audit',$/m);
  });
});
